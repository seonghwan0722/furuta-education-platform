function file = sp_write_rl_wrapper(outDir,name,policyFn,gate,thOffsetDeg)
% Wrap a stateless policy function a=policyFn(obs5) as a ControllerFunction [u,balancing]=name(x,active)
% for build_furuta_pi_hardware. x = [arm; pend; filtered arm rate; filtered pend rate] (Pi decoder output).
% gate=true: balance-only first-test version. Command is 0 until |pend err|<10 deg and |pend rate|<2 rad/s,
% then the policy runs until |pend err| exceeds 30 deg (then 0 again until re-captured).
tag=""; if gate, tag=" (balance-only gate)"; end
if nargin<5, thOffsetDeg=0; end   % pendulum zero trim (hardware 2026-11-20: 2.77 deg); sensor JSON untouched
L=[ "function [u,balancing] = "+name+"(x,active)"
"%#codegen"
"% Generated by sp_write_rl_wrapper around "+policyFn+tag
"persistent on"
"if isempty(on), on=false; end"
"x=double(x(:)); u=0; balancing=false;"
"x(2)=x(2)-"+sprintf('%.17g',deg2rad(thOffsetDeg))+";   % pendulum zero trim [rad]"
"if ~active, on=false; return; end"
"th=atan2(sin(x(2)),cos(x(2)));"
"o=[cos(x(2)); sin(x(2)); x(1); x(3); x(4)];"];
if gate
    L=[L
"if on && abs(th)>30*pi/180, on=false; end"
"if ~on && abs(th)<10*pi/180 && abs(x(4))<2, on=true; end"
"if on, u="+policyFn+"(o); end"
"balancing=on;"];
else
    L=[L
"u="+policyFn+"(o);"
"balancing=abs(th)<20*pi/180;"];
end
L=[L; "u=max(-1,min(1,u(1)));"; "end"];
file=fullfile(outDir,name+".m"); writelines(L,file);
end
