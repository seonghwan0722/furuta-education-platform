function file = sp_export_infer(agent,outDir,name)
% Write a plain-MATLAB (codegen-able, no DL support package) forward pass of the greedy PPO actor.
% Input: Pi observation [cos th; sin th; arm(raw, rad); arm rate; pend rate]. The arm angle is wrapped inside.
net=getModel(getActor(agent)); P=net.Learnables;
W=@(l,p) double(extractdata(P.Value{P.Layer==l & P.Parameter==p}));
W1=W("fc1","Weights"); b1=W("fc1","Bias"); W2=W("fc2","Weights"); b2=W("fc2","Bias"); W3=W("fc3","Weights"); b3=W("fc3","Bias");
lines=[ "function a = "+name+"(obs)"
 "%#codegen"
 "% Greedy PPO swing-up/balance actor (generated by sp_export_infer). Output in [-1,1] = current/1.5 A."
 "o = obs(:);"
 "o(3) = atan2(sin(o(3)),cos(o(3)));"
 "h1 = tanh("+mat2str(W1,17)+"*o+"+mat2str(b1,17)+");"
 "h2 = tanh("+mat2str(W2,17)+"*h1+"+mat2str(b2,17)+");"
 "a = tanh("+mat2str(W3,17)+"*h2+"+mat2str(b3,17)+");"
 "end"];
file=fullfile(outDir,name+".m"); writelines(lines,file);
addpath(outDir); fn=str2func(name); pol=getGreedyPolicy(agent);
rng(5); for k=1:50
  th=2*pi*rand-pi; ph=4*pi*rand-2*pi; o=[cos(th);sin(th);ph;10*randn;10*randn];
  ow=o; ow(3)=atan2(sin(ph),cos(ph)); r=getAction(pol,{ow});
  assert(abs(fn(o)-double(r{1}))<1e-5,'export mismatch');
end
fprintf('EXPORT_OK %s (50 random obs match, raw arm angle wrapped inside)\n',file);
end
