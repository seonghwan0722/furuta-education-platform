"""Generate furuta_lmpc_rev22b_step.m in the same form as lm_export_step output (furuta_lmpc_rev11c_step.m)."""
import sys, os; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from specs import *
J11, J22 = C['rev11']['J_body'], C['rev22']['J_body']
PD = dict(REV22, alpha=0.022 - J11 + J22, coulomb=0.40, eta_phi=0.12, gam=0.9 * REV22['gam'])
D = design(PD, Q=(3, 10, 5, 5), qObs=(50, 200))
f = lambda v: '%.17g' % v
M = lambda A: '[' + ';'.join(' '.join(f(x) for x in row) for row in np.atleast_2d(A)) + ']'
p = PD
src = f"""function [u,balancing] = furuta_lmpc_rev22b_step(x,active)
%#codegen
% rev22 LMPC (2026-11-27, generated by rev22_control/code/gen_step.py in lm_export_step form).
% Design model: rev22 CAD (beta {p['beta']:.4e}, beta2 {p['beta2']:.4e}, delta {p['delta']:.4e}) with gam x0.9, alpha {p['alpha']:.4f},
% coulomb 0.40, eta_phi 0.12. Q=[3 10 5 5], R=1, N=20, qObs=[50 200], arm-rate constraint 13.5.
% Changes vs furuta_lmpc_rev11c_step: (1) observer predicts 2 steps (20 ms) ahead instead of 1,
% (2) swing-up braking allowed up to 0.2 (0.3 A) instead of 0, (3) swing-up arm-rate taper 8->12 rad/s (was 10->14).
% TH_OFFSET: pendulum zero trim [rad]. rev11 used 2.77 deg; MEASURE rev22 before driving the motor.
persistent xh c1 c2 bal home
TH_OFFSET=0;
x=double(x(:)); x(2)=x(2)-TH_OFFSET; u=0; balancing=false;
if isempty(xh) || ~active
    xh=[x(1);x(2);0;0]; c1=0; c2=0; bal=false; home=0;
    if ~active, u=0; balancing=false; return; end
else
    xp=lmRk4(xh,c2);
    e=[atan2(sin(x(1)-xp(1)),cos(x(1)-xp(1))); atan2(sin(x(2)-xp(2)),cos(x(2)-xp(2)))];
    xh=xp+{M(D['L'])}*e;
end
xf=lmRk4(lmRk4(xh,c1),c1);
th=atan2(sin(xf(2)),cos(xf(2))); w=xf(4); v=xf(3);
cap=abs(th)<0.3490658503988659 && abs(w)<4.5;
if cap && ~bal, home=xf(1); end
bal=(bal && abs(th)<0.69813170079773179) || cap;
if ~bal
    E=.5*{f(p['beta2'])}*w^2+{f(p['delta'])}*(cos(th)-1);
    d=sign(w*cos(th)); if d==0, d=1; end
    u=600*E*d;
    if (E+2*{f(p['delta'])})<0.001 && abs(th)>pi/2
        u=-sign(sin(th)); if u==0, u=-1; end
    end
    over=max(0,(abs(v)-8)/(4));
    if sign(u)==sign(v), u=u*max(0,1-over); end
else
    z=[max(-0.6,min(0.6,xf(1)-home)); th; v; w];
    H={M(D['H'])};
    f={M(D['Fq'])}*z;
    Gv={M(D['Gv'])};
    fv={M(D['Fv'])}*z;
    N=20;
    Ai=[eye(N);-eye(N);Gv;-Gv]; bi=[ones(2*N,1);13.5-fv;13.5+fv];
    opt=mpcActiveSetOptions;
    [U,st]=mpcActiveSetSolver(H,f,Ai,bi,zeros(0,N),zeros(0,1),false(4*N,1),opt);
    if st<=0
        [U,~]=mpcActiveSetSolver(H,f,[eye(N);-eye(N)],ones(2*N,1),zeros(0,N),zeros(0,1),false(2*N,1),opt);
    end
    u=U(1,1);
end
u=max(-1,min(1,u));
if ~bal && u~=0 && sign(u)~=sign(v) && abs(v)>1, u=sign(u)*min(abs(u),0.2); end
if bal && u~=0 && sign(u)~=sign(v) && abs(v)>4, u=sign(u)*min(abs(u),0.33); end
if bal, u=c1+max(-0.3,min(0.3,u-c1)); end
u=round(u*150)/150;
u=u(1); c2=c1; c1=u; balancing=logical(bal);
end

function x=lmRk4(x,a)
tau=3.15*a; h=0.002;
for i=1:5
    k1=f(x); k2=f(x+h/2*k1); k3=f(x+h/2*k2); k4=f(x+h*k3);
    x=x+h/6*(k1+2*k2+2*k3+k4);
end
    function y=f(z)
        s=sin(z(2)); c=cos(z(2)); vv=z(3); ww=z(4);
        dd={f(p['alpha'])}+{f(p['beta'])}*s^2; b={f(p['gam'])}*c;
        ff=tau-2*{f(p['beta'])}*s*c*vv*ww+{f(p['gam'])}*s*ww^2-{f(p['eta_phi'])}*vv-{f(p['coulomb'])}*sign(vv);
        gg={f(p['beta'])}*s*c*vv^2-{f(p['eta_theta'])}*ww+{f(p['delta'])}*s;
        dt=dd*{f(p['beta2'])}-b^2;
        y=[z(3);z(4);({f(p['beta2'])}*ff-b*gg)/dt;(dd*gg-b*ff)/dt];
    end
end
"""
open(sys.argv[1], 'w').write(src)
print('ok', len(src))
